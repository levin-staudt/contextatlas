// Generates apps/web/app/components/globe-land.ts, the land mask of the home page globe.
//
//   bun run globe:land                    download Natural Earth 1:110m land from jsDelivr
//   bun run globe:land -- land-110m.json  use a local copy of world-atlas@2/land-110m.json
//
// The globe samples a Fibonacci sphere of POINTS points; bit i of the mask (least significant bit first)
// says whether point i lies on land. `landVectors` in globe.tsx rebuilds the same sphere, so both sides
// must agree on POINTS, the point order and the bit order.

const POINTS = 16_000;
const SOURCE = "https://cdn.jsdelivr.net/npm/world-atlas@2/land-110m.json";
const OUT = new URL("../apps/web/app/components/globe-land.ts", import.meta.url);

type Point = [lon: number, lat: number];
type Topology = {
  transform: { scale: [number, number]; translate: [number, number] };
  arcs: [number, number][][];
  objects: {
    land: { geometries: ({ type: "Polygon"; arcs: number[][] } | { type: "MultiPolygon"; arcs: number[][][] })[] };
  };
};

const path = process.argv[2];
const topo: Topology = path ? await Bun.file(path).json() : await (await fetch(SOURCE)).json();

// TopoJSON arcs are delta-encoded and quantized.
const { scale, translate } = topo.transform;
const arcs = topo.arcs.map((arc) => {
  let x = 0;
  let y = 0;
  return arc.map(([dx, dy]): Point => {
    x += dx;
    y += dy;
    return [x * scale[0] + translate[0], y * scale[1] + translate[1]];
  });
});

// Rings crossing the antimeridian (Fiji, Chukotka, Wrangel Island) are unwrapped so their longitudes run on
// past ±180 instead of jumping across the map; points are then tested at lon and lon ± 360.
function ring(ids: number[]): Point[] {
  const points = ids.flatMap((id) => (id >= 0 ? arcs[id]! : arcs[~id]!.slice().reverse()));
  let shift = 0;
  return points.map(([lon, lat], i) => {
    if (i > 0) {
      const d = lon - points[i - 1]![0];
      if (d > 180) shift -= 360;
      else if (d < -180) shift += 360;
    }
    return [lon + shift, lat];
  });
}

const polygons = topo.objects.land.geometries
  .flatMap((geometry) => (geometry.type === "Polygon" ? [geometry.arcs] : geometry.arcs))
  .map((rings) => rings.map(ring));

function inRing(lon: number, lat: number, points: Point[]) {
  let inside = false;
  for (let i = 0, j = points.length - 1; i < points.length; j = i++) {
    const [xi, yi] = points[i]!;
    const [xj, yj] = points[j]!;
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

function onLand(lon: number, lat: number) {
  return [lon, lon + 360, lon - 360].some((x) =>
    polygons.some(([outer, ...holes]) => inRing(x, lat, outer!) && !holes.some((hole) => inRing(x, lat, hole))),
  );
}

const golden = Math.PI * (3 - Math.sqrt(5));
const mask = new Uint8Array(Math.ceil(POINTS / 8));
let count = 0;
for (let i = 0; i < POINTS; i++) {
  const y = 1 - (2 * (i + 0.5)) / POINTS;
  const lat = (Math.asin(y) * 180) / Math.PI;
  const lon = (Math.atan2(Math.sin(golden * i), Math.cos(golden * i)) * 180) / Math.PI;
  if (onLand(lon, lat)) {
    mask[i >> 3]! |= 1 << (i & 7);
    count++;
  }
}

await Bun.write(
  OUT,
  `/**
 * Land mask for the home page globe: bit i is set when point i of a ${POINTS}-point Fibonacci sphere lies on land.
 * Generated by scripts/globe-land.ts (bun run globe:land) from Natural Earth 1:110m land
 * (world-atlas@2/land-110m.json, public domain). Do not edit by hand.
 */
export const landPoints = ${POINTS};
export const landMask =
  "${Buffer.from(mask).toString("base64")}";
`,
);
console.log(`Wrote ${count} land points of ${POINTS} to ${OUT.pathname}`);
